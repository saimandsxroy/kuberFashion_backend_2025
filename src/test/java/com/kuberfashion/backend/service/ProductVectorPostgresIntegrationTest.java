package com.kuberfashion.backend.service;

import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;

import java.util.List;
import java.util.Map;

import static org.junit.jupiter.api.Assertions.*;

/**
 * Dedicated pgvector integration test executing real vector cosine distance (<=>) queries,
 * verifying model compatibility enforcement, price/stock filters, variant tracking, and fallback.
 * Runs against the pgvector-enabled PostgreSQL test database.
 */
class ProductVectorPostgresIntegrationTest {

    private JdbcTemplate jdbcTemplate;

    @BeforeEach
    void setUp() {
        DriverManagerDataSource dataSource = new DriverManagerDataSource();
        dataSource.setDriverClassName("org.postgresql.Driver");
        dataSource.setUrl(System.getenv().getOrDefault("DATABASE_URL", "jdbc:postgresql://localhost:5432/kuberfashion_test_vector?sslmode=disable"));
        dataSource.setUsername(System.getenv().getOrDefault("DATABASE_USERNAME", "kuberfashion_user"));
        dataSource.setPassword(System.getenv().getOrDefault("DATABASE_PASSWORD", ""));
        jdbcTemplate = new JdbcTemplate(dataSource);

        // 1. Ensure pgvector is active
        jdbcTemplate.execute("CREATE EXTENSION IF NOT EXISTS vector;");

        // 2. Setup clean test schema
        jdbcTemplate.execute("DROP TABLE IF EXISTS test_product_variants CASCADE;");
        jdbcTemplate.execute("DROP TABLE IF EXISTS test_products CASCADE;");

        jdbcTemplate.execute("""
            CREATE TABLE test_products (
                id BIGSERIAL PRIMARY KEY,
                name VARCHAR(200) NOT NULL,
                category VARCHAR(100),
                price NUMERIC(10,2) NOT NULL,
                in_stock BOOLEAN NOT NULL DEFAULT true,
                stock_quantity INT NOT NULL DEFAULT 10,
                inventory_tracking_mode VARCHAR(50) NOT NULL DEFAULT 'LEGACY',
                is_active BOOLEAN NOT NULL DEFAULT true,
                embedding vector(3),
                embedding_model VARCHAR(100)
            );
        """);

        jdbcTemplate.execute("""
            CREATE TABLE test_product_variants (
                id BIGSERIAL PRIMARY KEY,
                product_id BIGINT REFERENCES test_products(id) ON DELETE CASCADE,
                size VARCHAR(20),
                color VARCHAR(50),
                stock_quantity INT NOT NULL,
                active BOOLEAN NOT NULL DEFAULT true
            );
        """);

        // Create HNSW cosine index
        jdbcTemplate.execute("""
            CREATE INDEX IF NOT EXISTS idx_test_products_hnsw
            ON test_products USING hnsw (embedding vector_cosine_ops);
        """);
    }

    @AfterEach
    void tearDown() {
        if (jdbcTemplate != null) {
            jdbcTemplate.execute("DROP TABLE IF EXISTS test_product_variants CASCADE;");
            jdbcTemplate.execute("DROP TABLE IF EXISTS test_products CASCADE;");
        }
    }

    @Test
    @DisplayName("1. Real PostgreSQL cosine distance (<=>) correctly ranks vector candidates")
    void testRealVectorCosineDistanceRanking() {
        jdbcTemplate.update("INSERT INTO test_products (name, price, embedding, embedding_model) VALUES ('Item A', 1000, '[1.0, 0.0, 0.0]'::vector, 'gemini-embedding-2')");
        jdbcTemplate.update("INSERT INTO test_products (name, price, embedding, embedding_model) VALUES ('Item B', 1200, '[0.9, 0.1, 0.0]'::vector, 'gemini-embedding-2')");
        jdbcTemplate.update("INSERT INTO test_products (name, price, embedding, embedding_model) VALUES ('Item C', 1500, '[0.0, 1.0, 0.0]'::vector, 'gemini-embedding-2')");

        String sql = """
            SELECT name, (1.0 - (embedding <=> '[1.0, 0.0, 0.0]'::vector)) AS similarity
            FROM test_products
            WHERE embedding IS NOT NULL
              AND embedding_model = 'gemini-embedding-2'
            ORDER BY embedding <=> '[1.0, 0.0, 0.0]'::vector ASC;
        """;

        List<Map<String, Object>> rows = jdbcTemplate.queryForList(sql);
        assertEquals(3, rows.size());

        assertEquals("Item A", rows.get(0).get("name"));
        assertEquals(1.0, ((Number) rows.get(0).get("similarity")).doubleValue(), 0.001);

        assertEquals("Item B", rows.get(1).get("name"));
        assertTrue(((Number) rows.get(1).get("similarity")).doubleValue() > 0.95);

        assertEquals("Item C", rows.get(2).get("name"));
        assertEquals(0.0, ((Number) rows.get(2).get("similarity")).doubleValue(), 0.001);
    }

    @Test
    @DisplayName("2. Enforces model compatibility: excludes vectors generated by different models")
    void testModelCompatibilityEnforcement() {
        // Product 1 generated with the current active model 'gemini-embedding-2'
        jdbcTemplate.update("INSERT INTO test_products (name, price, embedding, embedding_model) VALUES ('Active Model Product', 1999, '[1.0, 0.0, 0.0]'::vector, 'gemini-embedding-2')");

        // Product 2 generated with an old or different model (e.g. legacy model)
        jdbcTemplate.update("INSERT INTO test_products (name, price, embedding, embedding_model) VALUES ('Outdated Model Product', 1999, '[1.0, 0.0, 0.0]'::vector, 'old-deprecated-model')");

        // Query executing with current active model 'gemini-embedding-2'
        String sql = """
            SELECT name, (1.0 - (embedding <=> '[1.0, 0.0, 0.0]'::vector)) AS similarity
            FROM test_products
            WHERE embedding IS NOT NULL
              AND embedding_model = ?
            ORDER BY embedding <=> '[1.0, 0.0, 0.0]'::vector ASC;
        """;

        List<Map<String, Object>> rows = jdbcTemplate.queryForList(sql, "gemini-embedding-2");
        assertEquals(1, rows.size(), "Only vectors produced by the active model must be compared");
        assertEquals("Active Model Product", rows.get(0).get("name"));
    }

    @Test
    @DisplayName("3. Exact price constraints strictly filter semantic vector candidates")
    void testPriceConstraintsOnVectorCandidates() {
        jdbcTemplate.update("INSERT INTO test_products (name, price, embedding, embedding_model) VALUES ('Luxury Silk Saree', 5000, '[1.0, 0.0, 0.0]'::vector, 'gemini-embedding-2')");
        jdbcTemplate.update("INSERT INTO test_products (name, price, embedding, embedding_model) VALUES ('Cotton Daily Saree', 1200, '[0.8, 0.2, 0.0]'::vector, 'gemini-embedding-2')");

        String sql = """
            SELECT name, price, (1.0 - (embedding <=> '[1.0, 0.0, 0.0]'::vector)) AS similarity
            FROM test_products
            WHERE embedding IS NOT NULL
              AND embedding_model = 'gemini-embedding-2'
              AND price <= 2000
            ORDER BY embedding <=> '[1.0, 0.0, 0.0]'::vector ASC;
        """;

        List<Map<String, Object>> rows = jdbcTemplate.queryForList(sql);
        assertEquals(1, rows.size(), "Only the saree under 2000 should pass the relational filter");
        assertEquals("Cotton Daily Saree", rows.get(0).get("name"));
        assertEquals(1200.0, ((Number) rows.get(0).get("price")).doubleValue(), 0.01);
    }

    @Test
    @DisplayName("4. Variant inventory tracking verifies variant stock for semantic matches")
    void testVariantStockConstraintsOnVectorCandidates() {
        jdbcTemplate.update("INSERT INTO test_products (id, name, price, inventory_tracking_mode, embedding, embedding_model) VALUES (1, 'Athletic Bra', 699, 'VARIANT', '[1.0, 0.0, 0.0]'::vector, 'gemini-embedding-2')");
        jdbcTemplate.update("INSERT INTO test_product_variants (product_id, size, color, stock_quantity) VALUES (1, 'M', 'PINK', 0)");

        jdbcTemplate.update("INSERT INTO test_products (id, name, price, inventory_tracking_mode, embedding, embedding_model) VALUES (2, 'Padded Sports Crop Top', 799, 'VARIANT', '[0.9, 0.1, 0.0]'::vector, 'gemini-embedding-2')");
        jdbcTemplate.update("INSERT INTO test_product_variants (product_id, size, color, stock_quantity) VALUES (2, 'M', 'PINK', 5)");

        String sql = """
            SELECT p.name, (1.0 - (p.embedding <=> '[1.0, 0.0, 0.0]'::vector)) AS similarity
            FROM test_products p
            WHERE p.embedding_model = 'gemini-embedding-2'
              AND p.id IN (
                SELECT pv.product_id
                FROM test_product_variants pv
                WHERE pv.size = 'M' AND pv.stock_quantity > 0 AND pv.active = true
            )
            ORDER BY p.embedding <=> '[1.0, 0.0, 0.0]'::vector ASC;
        """;

        List<Map<String, Object>> rows = jdbcTemplate.queryForList(sql);
        assertEquals(1, rows.size(), "Out of stock variant must be excluded");
        assertEquals("Padded Sports Crop Top", rows.get(0).get("name"));
    }

    @Test
    @DisplayName("5. Missing embeddings seamlessly fall back without query failure")
    void testMissingEmbeddingsFallback() {
        jdbcTemplate.update("INSERT INTO test_products (name, price, embedding, embedding_model) VALUES ('Embedded Jacket', 2500, '[1.0, 0.0, 0.0]'::vector, 'gemini-embedding-2')");
        jdbcTemplate.update("INSERT INTO test_products (name, price, embedding, embedding_model) VALUES ('Unembedded Denim Jacket', 1800, NULL, NULL)");

        String keyword = "%jacket%";
        String sql = """
            SELECT name, price,
                   CASE WHEN embedding IS NOT NULL
                        THEN (1.0 - (embedding <=> '[1.0, 0.0, 0.0]'::vector))
                        ELSE 0.0 END AS similarity
            FROM test_products
            WHERE (embedding IS NOT NULL AND embedding_model = 'gemini-embedding-2' AND (1.0 - (embedding <=> '[1.0, 0.0, 0.0]'::vector)) > 0.5)
               OR (LOWER(name) LIKE LOWER(?))
            ORDER BY similarity DESC, price ASC;
        """;

        List<Map<String, Object>> rows = jdbcTemplate.queryForList(sql, keyword);
        assertEquals(2, rows.size(), "Both products must be returned: one via vector similarity, one via keyword fallback");
        assertEquals("Embedded Jacket", rows.get(0).get("name"));
        assertEquals("Unembedded Denim Jacket", rows.get(1).get("name"));
    }

    @Test
    @DisplayName("6. Semantically similar wording matches relevant candidate items")
    void testSemanticWordingVariations() {
        jdbcTemplate.update("INSERT INTO test_products (name, price, embedding, embedding_model) VALUES ('Black Velvet Party Gown', 3500, '[0.85, 0.45, 0.25]'::vector, 'gemini-embedding-2')");
        jdbcTemplate.update("INSERT INTO test_products (name, price, embedding, embedding_model) VALUES ('Gym Running Shorts', 599, '[0.10, 0.05, 0.95]'::vector, 'gemini-embedding-2')");

        String queryVec = "[0.80, 0.50, 0.20]";
        String sql = """
            SELECT name, (1.0 - (embedding <=> ?::vector)) AS similarity
            FROM test_products
            WHERE embedding_model = 'gemini-embedding-2'
              AND (1.0 - (embedding <=> ?::vector)) > 0.70
            ORDER BY similarity DESC;
        """;

        List<Map<String, Object>> rows = jdbcTemplate.queryForList(sql, queryVec, queryVec);
        assertEquals(1, rows.size());
        assertEquals("Black Velvet Party Gown", rows.get(0).get("name"));
        assertTrue(((Number) rows.get(0).get("similarity")).doubleValue() > 0.95);
    }
}
